"""Prepare a HuggingFace `datasets`-loadable directory for diffusers'
official ControlNet fine-tuning script (train_controlnet.py), from the
Phase 1 paired corpus's {train,val,test}/<id>_condition.png +
<id>_target.jpg layout.

diffusers' train_controlnet.py calls datasets.load_dataset(args.train_data_dir)
on a local directory, which datasets resolves to a same-named loading
script inside that directory (the documented pattern for local ControlNet
training data, e.g. the "fill50k" example). This module's list_pairs() is
the file-pairing logic; the GeneratorBasedBuilder below is the thin glue
datasets.load_dataset() expects, kept in the corpus directory itself so the
directory is self-contained.
"""

from pathlib import Path

CAPTION = "a photorealistic Mars rover Navcam photograph of the martian surface"


def list_pairs(split_dir: Path) -> list[tuple[Path, Path]]:
    """Return (target_path, condition_path) for every complete pair in
    split_dir, sorted by product id for determinism. Silently skips a
    target with no matching condition file (shouldn't happen given how
    assemble_paired_corpus.py writes them, but a directory could in
    principle be edited by hand)."""
    pairs = []
    for target_path in sorted(split_dir.glob("*_target.jpg")):
        product_id = target_path.name.removesuffix("_target.jpg")
        condition_path = split_dir / f"{product_id}_condition.png"
        if condition_path.exists():
            pairs.append((target_path, condition_path))
    return pairs


def write_loading_script(corpus_dir: Path) -> Path:
    """Write the datasets.GeneratorBasedBuilder loading script into
    corpus_dir, named to match the directory (datasets' local-script
    convention). Idempotent -- overwrites any prior version."""
    script_path = corpus_dir / f"{corpus_dir.name}.py"
    script_path.write_text(f'''"""Auto-generated by prepare_controlnet_hf_dataset.py -- do not hand-edit."""
import os
import datasets

CAPTION = {CAPTION!r}


class PairedControlnetCorpus(datasets.GeneratorBasedBuilder):
    VERSION = datasets.Version("1.0.0")

    def _info(self):
        return datasets.DatasetInfo(
            features=datasets.Features({{
                "image": datasets.Image(),
                "conditioning_image": datasets.Image(),
                "text": datasets.Value("string"),
            }}),
        )

    def _split_generators(self, dl_manager):
        base = os.path.dirname(__file__)
        return [
            datasets.SplitGenerator(
                name=datasets.Split.TRAIN,
                gen_kwargs={{"split_dir": os.path.join(base, "train")}},
            ),
        ]

    def _generate_examples(self, split_dir):
        idx = 0
        for fname in sorted(os.listdir(split_dir)):
            if not fname.endswith("_target.jpg"):
                continue
            product_id = fname[: -len("_target.jpg")]
            condition_path = os.path.join(split_dir, f"{{product_id}}_condition.png")
            if not os.path.exists(condition_path):
                continue
            yield idx, {{
                "image": os.path.join(split_dir, fname),
                "conditioning_image": condition_path,
                "text": CAPTION,
            }}
            idx += 1
''')
    return script_path


if __name__ == "__main__":
    import sys

    corpus_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else (
        Path(__file__).parent.parent / "Data" / "processed" / "paired_controlnet_corpus"
    )
    n_train = len(list_pairs(corpus_dir / "train"))
    n_val = len(list_pairs(corpus_dir / "val"))
    n_test = len(list_pairs(corpus_dir / "test"))
    print(f"train={n_train} val={n_val} test={n_test}")
    script_path = write_loading_script(corpus_dir)
    print(f"Wrote loading script: {script_path}")
